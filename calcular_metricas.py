#!/usr/bin/env python3
"""
make_results_tables.py
======================
Genera las tablas LaTeX de resultados a partir de runs/summary.csv.

Salidas (por defecto en ./runs/):
  runs/e2e-results.tex
  runs/recovery-results.tex

Puedes cambiar la carpeta de salida con --out:
  python3 make_results_tables.py --out tables/en

Filtros aplicados:
  - Excluye deepseek (Tier 4: emite prosa CoT, no DDL)
  - Excluye filas con BLEU < 0.05 (LLM emitió markdown)
  - Promedia sobre los LLMs y DBs restantes

Uso:
  python3 make_results_tables.py
  python3 make_results_tables.py --out tables/en
  python3 make_results_tables.py --csv runs/summary.csv --out runs
"""
import argparse
import csv
import os
from collections import defaultdict

SCHEMAS_ORDER = ["basico", "biblio", "innova", "northwind", "postulaciones"]
MODES_ORDER = ["llm_only", "rag", "rag_validation"]


def to_f(x):
    try:
        return float(x) if x and x.strip() else None
    except (ValueError, AttributeError):
        return None


def mean(vals):
    return sum(vals) / len(vals) if vals else None


def fmt(v, nd=3):
    return "--" if v is None else f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default="runs/summary.csv",
                    help="Path to summary.csv (default: runs/summary.csv)")
    ap.add_argument("--out", default="runs",
                    help="Output directory for generated .tex (default: runs)")
    args = ap.parse_args()

    if not os.path.exists(args.csv):
        raise SystemExit(f"[ERROR] No existe: {args.csv}")
    os.makedirs(args.out, exist_ok=True)

    out_e2e = os.path.join(args.out, "e2e-results.tex")
    out_ret = os.path.join(args.out, "recovery-results.tex")

    # --- Load and filter ---
    with open(args.csv) as f:
        rows = list(csv.DictReader(f))

    filtered = []
    for r in rows:
        if r["llm"].startswith("deepseek"):
            continue
        b = to_f(r.get("bleu"))
        if b is not None and b < 0.05:
            continue
        filtered.append(r)

    print(f"CSV:             {args.csv}")
    print(f"Filas totales:   {len(rows)}")
    print(f"Filas para paper: {len(filtered)}")
    print()

    # --- Aggregate structural metrics by (schema, mode) ---
    agg = defaultdict(lambda: defaultdict(list))
    for r in filtered:
        key = (r["schema"], r["mode"])
        for m in ["table_acc", "f1", "fk_acc", "full_schema",
                  "faith", "bleu", "iters"]:
            v = to_f(r.get(m))
            if v is not None:
                agg[key][m].append(v)

    # --- Table 1: e2e-results.tex ---
    with open(out_e2e, "w") as f:
        f.write("% Auto-generated by make_results_tables.py -- do not edit manually\n")
        f.write("\\begin{table*}[htbp]\n\\centering\\scriptsize\n")
        f.write("\\setlength{\\tabcolsep}{4pt}\n")
        f.write("\\caption{End-to-end structural and language results, averaged "
                "over three LLMs (\\texttt{llama3.2}, \\texttt{qwen2.5}, "
                "\\texttt{gemma2}) and three database backends (SQLite, MySQL, "
                "PostgreSQL). Each row aggregates all runs of one schema under "
                "one execution mode. \\textbf{TA}: Table Accuracy; \\textbf{F1}: "
                "structural F1; \\textbf{FK}: foreign-key accuracy; "
                "\\textbf{Full}: Full-Schema accuracy; \\textbf{Faith}: structural "
                "Faithfulness; \\textbf{Iters}: correction-loop iterations "
                "(\\texttt{rag\\_validation} only).}\n")
        f.write("\\label{tab:e2e_results}\n")
        f.write("\\resizebox{\\textwidth}{!}{%\n")
        f.write("\\begin{tabular}{llcccccc}\n\\toprule\n")
        f.write("\\textbf{Schema} & \\textbf{Mode} & \\textbf{TA} & "
                "\\textbf{F1} & \\textbf{FK} & \\textbf{Full} & "
                "\\textbf{Faith} & \\textbf{Iters} \\\\\n")
        f.write("\\midrule\n")
        for schema in SCHEMAS_ORDER:
            first = True
            for mode in MODES_ORDER:
                vals = agg.get((schema, mode), {})
                if not vals:
                    continue
                label = schema if first else ""
                first = False
                mode_str = mode.replace("_", "\\_")
                f.write(
                    f"{label} & {mode_str} & "
                    f"{fmt(mean(vals.get('table_acc', [])))} & "
                    f"{fmt(mean(vals.get('f1', [])))} & "
                    f"{fmt(mean(vals.get('fk_acc', [])))} & "
                    f"{fmt(mean(vals.get('full_schema', [])))} & "
                    f"{fmt(mean(vals.get('faith', [])))} & "
                    f"{fmt(mean(vals.get('iters', [])), nd=1)} \\\\\n"
                )
            if schema != SCHEMAS_ORDER[-1]:
                f.write("\\midrule\n")
        f.write("\\bottomrule\n\\end{tabular}%\n}\n\\end{table*}\n")
    print(f"[OK] {out_e2e}")

    # --- Aggregate retrieval metrics by schema (invariant to mode/LLM) ---
    ret_agg = defaultdict(lambda: defaultdict(list))
    for r in filtered:
        key = r["schema"]
        for m in ["map", "map_plus", "p5", "r5", "ndcg5"]:
            v = to_f(r.get(m))
            if v is not None:
                ret_agg[key][m].append(v)

    # --- Table 2: recovery-results.tex ---
    with open(out_ret, "w") as f:
        f.write("% Auto-generated by make_results_tables.py -- do not edit manually\n")
        f.write("\\begin{table}[htbp]\n\\centering\\footnotesize\n")
        f.write("\\setlength{\\tabcolsep}{3pt}\n")
        f.write("\\caption{Retrieval metrics at $K=5$, averaged across all "
                "LLMs and database backends. Retrieval quality is determined by "
                "the embedding model and vector store, so it is invariant to "
                "the execution mode.}\n")
        f.write("\\label{tab:recovery_results}\n")
        f.write("\\begin{tabular}{lccccc}\n\\toprule\n")
        f.write("\\textbf{Schema} & \\textbf{MAP} & \\textbf{MAP$^+$} & "
                "\\textbf{P@5} & \\textbf{R@5} & \\textbf{NDCG@5} \\\\\n")
        f.write("\\midrule\n")
        overall = defaultdict(list)
        for schema in SCHEMAS_ORDER:
            vals = ret_agg.get(schema, {})
            if not vals:
                continue
            f.write(
                f"{schema} & "
                f"{fmt(mean(vals.get('map', [])))} & "
                f"{fmt(mean(vals.get('map_plus', [])))} & "
                f"{fmt(mean(vals.get('p5', [])))} & "
                f"{fmt(mean(vals.get('r5', [])))} & "
                f"{fmt(mean(vals.get('ndcg5', [])))} \\\\\n"
            )
            for m in ["map", "map_plus", "p5", "r5", "ndcg5"]:
                overall[m].extend(vals.get(m, []))
        f.write("\\midrule\n")
        f.write(
            f"\\textbf{{Overall}} & "
            f"\\textbf{{{fmt(mean(overall['map']))}}} & "
            f"\\textbf{{{fmt(mean(overall['map_plus']))}}} & "
            f"\\textbf{{{fmt(mean(overall['p5']))}}} & "
            f"\\textbf{{{fmt(mean(overall['r5']))}}} & "
            f"\\textbf{{{fmt(mean(overall['ndcg5']))}}} \\\\\n"
        )
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"[OK] {out_ret}")


if __name__ == "__main__":
    main()